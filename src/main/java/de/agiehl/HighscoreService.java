package de.agiehl;

import java.sql.ResultSet;
import java.sql.SQLException;
import java.text.Normalizer;
import java.time.Clock;
import java.time.OffsetDateTime;
import java.time.ZoneOffset;
import org.springframework.dao.DuplicateKeyException;
import org.springframework.http.HttpStatus;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Service;

@Service
public class HighscoreService {

    private static final String RANKED_ENTRIES = """
            SELECT game_id, name, score, correct_answers, distance,
                   ROW_NUMBER() OVER (ORDER BY score DESC, correct_answers DESC, created_at ASC, id ASC) AS position
            FROM highscores
            """;
    private final JdbcTemplate jdbc;
    private final GameService games;
    private final Clock clock;

    public HighscoreService(JdbcTemplate jdbc, GameService games, Clock clock) {
        this.jdbc = jdbc;
        this.games = games;
        this.clock = clock;
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS highscores (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    game_id VARCHAR(36) NOT NULL UNIQUE,
                    name VARCHAR(48) NOT NULL,
                    score BIGINT NOT NULL,
                    correct_answers INTEGER NOT NULL,
                    distance BIGINT NOT NULL,
                    created_at TIMESTAMP WITH TIME ZONE NOT NULL
                )
                """);
        jdbc.execute("ALTER TABLE highscores ALTER COLUMN name VARCHAR(48) NOT NULL");
    }

    public Leaderboard leaderboard() {
        return result(null);
    }

    public Leaderboard save(String owner, HighscoreRequest request) {
        if (request == null || request.gameId() == null || request.gameId().isBlank()) {
            throw new IllegalArgumentException("Der Flug für dein Ergebnis fehlt.");
        }
        var game = games.get(owner, request.gameId());
        if (!game.phase().equals("FINISHED")) {
            throw new GameException(HttpStatus.CONFLICT, "Beende deinen Flug, bevor du dein Ergebnis speicherst.");
        }
        var saved = ownEntry(request.gameId());
        if (saved != null) {
            return result(saved);
        }
        String name = normalizeName(request.name());
        try {
            jdbc.update("""
                    INSERT INTO highscores (game_id, name, score, correct_answers, distance, created_at)
                    VALUES (?, ?, ?, ?, ?, ?)
                    """, request.gameId(), name, game.score(), game.correctAnswers(), game.distance(),
                    OffsetDateTime.ofInstant(clock.instant(), ZoneOffset.UTC));
        } catch (DuplicateKeyException _) {
            return result(ownEntry(request.gameId()));
        }
        return result(ownEntry(request.gameId()));
    }

    static String normalizeName(String value) {
        if (value == null || value.length() > 1_000) {
            throw new IllegalArgumentException("Trage einen Namen mit bis zu 24 Zeichen ein.");
        }
        String normalized = Normalizer.normalize(value, Normalizer.Form.NFC)
                .replaceAll("[\\p{Z}\\s]+", " ")
                .replaceAll("[\\p{Cc}\\p{Cf}]", "").strip();
        if (normalized.isBlank()) {
            throw new IllegalArgumentException("Trage einen Namen für die Bestenliste ein.");
        }
        if (normalized.codePointCount(0, normalized.length()) > 24) {
            normalized = normalized.substring(0, normalized.offsetByCodePoints(0, 24)).stripTrailing();
        }
        return normalized;
    }

    private Leaderboard result(HighscoreEntry own) {
        var entries = jdbc.query("SELECT * FROM (" + RANKED_ENTRIES + ") ranked ORDER BY position FETCH FIRST 3 ROWS ONLY",
                this::mapEntry);
        return new Leaderboard(entries, own);
    }

    private HighscoreEntry ownEntry(String gameId) {
        var entries = jdbc.query("SELECT * FROM (" + RANKED_ENTRIES + ") ranked WHERE game_id = ?",
                this::mapEntry, gameId);
        return entries.isEmpty() ? null : entries.getFirst();
    }

    private HighscoreEntry mapEntry(ResultSet row, int rowNumber) throws SQLException {
        return new HighscoreEntry(row.getString("name"), row.getLong("score"), row.getInt("correct_answers"),
                row.getLong("distance"), row.getLong("position"));
    }
}
